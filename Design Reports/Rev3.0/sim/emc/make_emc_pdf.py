def P(t, st=N): return Paragraph(t, st)
def tbl(rows, widths=None, head=True, font=7.5):
    data = [[Paragraph(str(c), CELL) if isinstance(c, str) and len(c) > 28 else c for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1 if head else 0)
    st = [("FONT", (0, 0), (-1, -1), "Helvetica", font), ("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
          ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3)]
    if head: st += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e3e8f0")), ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", font)]
    t.setStyle(TableStyle(st)); return t
def img(name, w=160 * mm):
    p = os.path.join(HERE, name)
    from reportlab.lib.utils import ImageReader
    iw, ih = ImageReader(p).getSize(); return Image(p, width=w, height=w * ih / iw)
