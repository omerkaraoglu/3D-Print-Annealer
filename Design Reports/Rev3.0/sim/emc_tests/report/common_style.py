def _plain_decade(self, x, pos=None):
    if x <= 0:
        return ""
    e = math.log10(x)
    if abs(e - round(e)) > 1e-6:
        return ""
    e = int(round(e))
    return ("%d" % round(x)) if e >= 0 else ("%.*f" % (-e, x))


