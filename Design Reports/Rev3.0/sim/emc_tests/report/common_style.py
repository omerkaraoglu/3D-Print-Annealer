OVERLAPS = []          # (chart, text, obstacle) collected over a make_charts run
CLEAR_PT = 1.5         # required clearance between a text box and any plotted line, marker, bar / band edge or reference line


def _seg_hits(seg, r):
    """Liang-Barsky: which segments (N x 4: x0 y0 x1 y1) touch rectangle r = (xmin, ymin, xmax, ymax)"""
    if len(seg) == 0:
        return np.zeros(0, bool)
    x0, y0, x1, y1 = seg.T
    dx, dy = x1 - x0, y1 - y0
    u0 = np.zeros(len(seg)); u1 = np.ones(len(seg)); ok = np.isfinite(seg).all(axis=1)
    for p, q in ((-dx, x0 - r[0]), (dx, r[2] - x0), (-dy, y0 - r[1]), (dy, r[3] - y0)):
        zero = np.abs(p) < 1e-12
        ok &= ~(zero & (q < 0))
        with np.errstate(divide="ignore", invalid="ignore"):
            t = np.where(zero, 0.0, q / np.where(zero, 1.0, p))
        u0 = np.where(~zero & (p < 0), np.maximum(u0, t), u0)
        u1 = np.where(~zero & (p > 0), np.minimum(u1, t), u1)
    return ok & (u0 <= u1)


def _poly_segments(verts, closed=False):
    v = np.asarray(verts, float)
    if len(v) < 2:
        return np.zeros((0, 4))
    if closed:
        v = np.vstack([v, v[:1]])
    return np.hstack([v[:-1], v[1:]])


def collect_obstacles(fig, skip_extra=()):
    """display-coordinate obstacles: (segments N x 4, points N x 2, marker half-size px, clip bbox, description, artist id, gid).
    Excluded: grid lines, ticks, spines, axes/figure background, images, legend internals and text boxes."""
    import matplotlib.lines as mlines, matplotlib.patches as mpatches, matplotlib.collections as mcoll, matplotlib.spines as mspines
    import matplotlib.legend as mlegend
    px = fig.dpi / 72.0
    skip = set(id(a) for a in skip_extra)
    for ax in fig.axes:
        for axis in (ax.xaxis, ax.yaxis):
            for g in axis.get_gridlines():
                skip.add(id(g))
            for tick in axis.get_major_ticks() + axis.get_minor_ticks():
                for a in (tick.tick1line, tick.tick2line, tick.gridline):
                    skip.add(id(a))
        skip.add(id(ax.patch))
    skip.add(id(fig.patch))
    for lg in fig.findobj(mlegend.Legend):
        for a in lg.findobj():
            skip.add(id(a))
    for t in fig.findobj(matplotlib.text.Text):
        if t.get_bbox_patch() is not None:
            skip.add(id(t.get_bbox_patch()))
    obs = []
    def clipbox(a):
        return a.get_clip_box() if a.get_clip_on() and a.get_clip_box() is not None else None
    for ln in fig.findobj(mlines.Line2D):
        if id(ln) in skip or not ln.get_visible():
            continue
        d = ln.get_xydata()
        xy = ln.get_transform().transform(d) if len(d) else np.zeros((0, 2))
        seg = _poly_segments(xy) if ln.get_linestyle() not in ("None", "", " ", "none") else np.zeros((0, 4))
        mk = ln.get_marker()
        pts = xy if mk not in (None, "None", "", " ", "none") else np.zeros((0, 2))
        obs.append((seg, pts, (ln.get_markersize() + ln.get_markeredgewidth()) / 2 * px, clipbox(ln), "line %s" % (ln.get_label() or ""), id(ln), ln.get_gid()))
    for pa in fig.findobj(mpatches.Patch):
        if id(pa) in skip or not pa.get_visible() or isinstance(pa, mspines.Spine):
            continue
        if pa.get_edgecolor()[3] == 0 and pa.get_facecolor()[3] == 0:
            continue
        path = pa.get_transform().transform_path(pa.get_path())
        segs = [_poly_segments(poly) for poly in path.to_polygons(closed_only=False)]
        seg = np.vstack(segs) if segs else np.zeros((0, 4))
        obs.append((seg, np.zeros((0, 2)), 0, clipbox(pa), type(pa).__name__, id(pa), pa.get_gid()))
    for co in fig.findobj(mcoll.Collection):
        if id(co) in skip or not co.get_visible():
            continue
        offs = co.get_offsets()
        if isinstance(co, mcoll.PathCollection) and len(offs):
            pts = co.get_offset_transform().transform(offs)
            sz = np.sqrt(np.max(co.get_sizes())) / 2 * px if len(co.get_sizes()) else 3 * px
            obs.append((np.zeros((0, 4)), pts, sz, clipbox(co), "scatter", id(co), co.get_gid()))
            continue
        tr = co.get_transform()
        segs = []
        for path in co.get_paths():
            for poly in tr.transform_path(path).to_polygons(closed_only=False):
                segs.append(_poly_segments(poly))
        if segs:
            obs.append((np.vstack(segs), np.zeros((0, 2)), 0, clipbox(co), type(co).__name__, id(co), co.get_gid()))
    return obs


def bbox_hits(bb, obs, fig, own=(), gid=None):
    """obstacles touched by display bbox bb (with CLEAR_PT clearance); own = artist ids to ignore; badge gids pair up"""
    clr = CLEAR_PT * fig.dpi / 72.0
    r0 = (bb.x0 - clr, bb.y0 - clr, bb.x1 + clr, bb.y1 + clr)
    out = []
    for seg, pts, half, cb, desc, aid, ogid in obs:
        if aid in own or (gid is not None and ogid == gid):
            continue
        r = r0
        if cb is not None:
            r = (max(r[0], cb.x0), max(r[1], cb.y0), min(r[2], cb.x1), min(r[3], cb.y1))
            if r[0] >= r[2] or r[1] >= r[3]:
                continue
        hit = bool(_seg_hits(seg, r).any())
        if not hit and len(pts):
            inside = (pts[:, 0] >= r[0] - half) & (pts[:, 0] <= r[2] + half) & (pts[:, 1] >= r[1] - half) & (pts[:, 1] <= r[3] + half)
            hit = bool(inside.any())
        if hit:
            out.append(desc)
    return out


def _text_box(t, rend):
    bp = t.get_bbox_patch()
    if bp is not None:
        t.update_bbox_position_size(rend)
        return bp.get_window_extent(rend)
    return matplotlib.text.Text.get_window_extent(t, rend)     # for an Annotation: the text only, not its leader


def check_overlaps(fig, name):
    """every visible text against every obstacle (badge pairs and an annotation's own leader excepted)"""
    fig.canvas.draw()
    rend = fig.canvas.get_renderer()
    obs = collect_obstacles(fig)
    texts = [t for t in fig.findobj(matplotlib.text.Text) if t.get_visible() and t.get_text().strip()]
    hits = []
    for t in texts:
        own = set()
        if getattr(t, "arrow_patch", None) is not None:
            own.add(id(t.arrow_patch))
        for d in bbox_hits(_text_box(t, rend), obs, fig, own=own, gid=t.get_gid()):
            hits.append((name, t.get_text().replace("\n", " ")[:50], d[:40]))
    return hits


class Placer:
    """put a label at the first candidate position that touches no obstacle and no label placed before"""
    def __init__(self, fig):
        fig.canvas.draw()
        self.fig = fig; self.rend = fig.canvas.get_renderer()
        self.obs = collect_obstacles(fig)
        self.boxes = [_text_box(t, self.rend) for t in fig.findobj(matplotlib.text.Text) if t.get_visible() and t.get_text().strip()]

    def place(self, ax, cands, s, **kw):
        """cands: list of (x, y, ha, va) in data coordinates, or (x, y, ha, va, dx_pt, dy_pt)"""
        from matplotlib.transforms import offset_copy
        clr = CLEAR_PT * self.fig.dpi / 72.0
        first = None
        for c in cands:
            x, y, ha, va = c[:4]
            dx, dy = (c[4], c[5]) if len(c) > 4 else (0, 0)
            tr = offset_copy(kw.pop("transform", ax.transData), fig=self.fig, x=dx, y=dy, units="points")
            t = ax.text(x, y, s, ha=ha, va=va, transform=tr, **kw)
            bb = _text_box(t, self.rend)
            okfig = bb.x0 >= self.fig.bbox.x0 and bb.x1 <= self.fig.bbox.x1 and bb.y0 >= self.fig.bbox.y0 and bb.y1 <= self.fig.bbox.y1
            ab = ax.get_window_extent(self.rend)
            okfig = okfig and bb.x0 >= ab.x0 and bb.x1 <= ab.x1 and bb.y0 >= ab.y0 and bb.y1 <= ab.y1
            bad = (not okfig) or bbox_hits(bb, self.obs, self.fig) or any(
                bb.x0 - clr < o.x1 and o.x0 < bb.x1 + clr and bb.y0 - clr < o.y1 and o.y0 < bb.y1 + clr for o in self.boxes)
            if not bad:
                self.boxes.append(bb)
                return t
            if first is None:
                first = c
            t.remove()
        x, y, ha, va = first[:4]
        dx, dy = (first[4], first[5]) if len(first) > 4 else (0, 0)
        t = ax.text(x, y, s, ha=ha, va=va, transform=offset_copy(ax.transData, fig=self.fig, x=dx, y=dy, units="points"), **kw)
        print("  PLACER: no free position for %r" % s)
        self.boxes.append(_text_box(t, self.rend))
        return t


def save(fig, name):
    # guard 1: no text may extend beyond the figure (it would be clipped on the page)
    fig.canvas.draw()
    rend = fig.canvas.get_renderer(); fb = fig.bbox
    hidden = set()
    for ax in fig.axes:
        for axis in (ax.xaxis, ax.yaxis):
            lo, hi = sorted(axis.get_view_interval())
            for tick in axis.get_major_ticks() + axis.get_minor_ticks():
                if not (lo - 1e-9 * abs(hi - lo) <= tick.get_loc() <= hi + 1e-9 * abs(hi - lo)):
                    hidden.update((id(tick.label1), id(tick.label2)))
                    tick.label1.set_visible(False); tick.label2.set_visible(False)
    for t in fig.findobj(matplotlib.text.Text):
        if not t.get_visible() or not t.get_text().strip() or id(t) in hidden:
            continue
        bb = t.get_window_extent(rend)
        if bb.x0 < fb.x0 - 0.5 or bb.x1 > fb.x1 + 0.5 or bb.y0 < fb.y0 - 0.5 or bb.y1 > fb.y1 + 0.5:
            print("  WARNING %s: text outside the figure: %r" % (name, t.get_text()[:60]))
    # guard 2: text against plotted lines, markers, bar / band edges, reference lines
    hits = check_overlaps(fig, name)
    for h in hits:
        print("  OVERLAP %s: [%s] x %s" % h)
    OVERLAPS.extend(hits)
    fig.savefig(os.path.join(CH, name + ".pdf"))
    fig.savefig(os.path.join(CH, name + ".png"), dpi=110)
    plt.close(fig)
    print("chart", name)


def hline(ax, y, text, x=0.995, va="bottom", ha="right", color=LIM, ls="--", lw=1.1, fs=8, dy=0, **kw):
    ax.axhline(y, color=color, ls=ls, lw=lw, zorder=2)
    t = ax.text(x, y, text, transform=ax.get_yaxis_transform(), ha=ha, va=va, fontsize=fs, color=color, zorder=5, **kw)
    dy = dy or (-3.0 if va == "top" else 3.0 if va == "bottom" else 0)
    if dy:
        from matplotlib.transforms import offset_copy
        t.set_transform(offset_copy(t.get_transform(), fig=ax.figure, y=dy, units="points"))
    return t


def vline(ax, x, text, y=0.98, ha="left", va="top", color=LIM, ls="--", lw=1.1, fs=8, rot=0, **kw):
    ax.axvline(x, color=color, ls=ls, lw=lw, zorder=2)
    return ax.text(x, y, text, transform=ax.get_xaxis_transform(), ha=ha, va=va, fontsize=fs, color=color, rotation=rot, zorder=5, **kw)


def tag(ax, x, y, verdict, text=None, fs=8, ha="center", va="center", transform=None, **kw):
    fg, bg = VERD[verdict]
    return ax.text(x, y, text or verdict, fontsize=fs, color=fg, ha=ha, va=va, fontweight="bold",
                   bbox=dict(boxstyle="round,pad=0.25", fc=bg, ec=fg, lw=0.6), transform=transform or ax.transData, zorder=6, **kw)


